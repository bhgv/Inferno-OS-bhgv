#!/usr/bin/env python3
"""Run protected result cleanup through actual heap/collector and both port kprotect bodies."""
import os
from pathlib import Path
import resource
import runpy
import shlex
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parents[2]
GC = runpy.run_path(str(ROOT/'utils/tests/native64-gc.py'))
SUPPORT = {'__file__': str(ROOT/'libinterp/tests/dis64-runtime.py'), '__name__': 'result_source_support'}
exec(compile((ROOT/'libinterp/tests/dis64-runtime.py').read_bytes(), SUPPORT['__file__'], 'exec'), SUPPORT)
function = SUPPORT['function']


# Preserve complete actual protection/read bodies and control only platform jump/allocation services.
def unit(port):
    source = GC['unit']()
    for signature in ('void\nerror(', 'int\nkprotect(', 'void\nkrethrow('):
        source = source.replace(function(source, signature), '', 1)
    source = source.replace('int\nmain(int argc, char **argv)', 'int\nnative64_root_main(int argc, char **argv)', 1)
    collector = (ROOT/'libinterp/gc.c').read_text()
    collector = '\n'.join(line for line in collector.splitlines() if not line.startswith('#include'))
    allocation = '''static int failpin; // Inject failure only at actual ptradd's metadata allocation.


/* Preserve every production collector statement around its native allocation boundary. */
static void*
resultmalloc(size_t bytes)
{
    return failpin ? nil : malloc(bytes);
}

#define malloc(bytes) resultmalloc(bytes) // Only the complete collector body below uses this boundary.
'''
    source = source.replace(collector, allocation+collector+'\n#undef malloc\n', 1)
    runtime = (ROOT/port/'port/dis.c').read_text()
    read = (ROOT/port/'port'/('errstr.c' if port == 'emu' else 'proc.c')).read_text()
    copy = (ROOT/port/'port/chan.c').read_text()
    bodies = '\n\n'.join((function(runtime, 'int\nkprotect('), function(runtime, 'void\nkrethrow('),
                           function(copy, 'void\nkstrcpy('), function(read, 'void\nkgerrstr(')))
    return source+(ROOT/'utils/tests/native64-result.c').read_text().replace('PROTECTED_IMPLEMENTATION', bodies)


# Match real generated byte-array caller storage to the selected C result owner profile.
def main():
    resource.setrlimit(resource.RLIMIT_CORE, (0, 0))
    env = dict(os.environ)
    flags = shlex.split(env.get('NATIVE64_CFLAGS', '-O1 -g -fno-strict-aliasing -fsanitize=undefined -fno-sanitize-recover=all'))
    compiler = shlex.split(env.get('CC', 'cc'))
    with tempfile.TemporaryDirectory(prefix='native64-result-') as temporary:
        work = Path(temporary)
        if env.get('NATIVE64_LIMBO'):
            limbo = Path(env['NATIVE64_LIMBO']).resolve()
        else:
            build = dict(env, CFLAGS=shlex.join(flags), INFERNO_ROOT=str(ROOT), MKBOOTSTRAP_LIMBO='1', MKBOOTSTRAP_BINDIR=str(work/'tools'))
            GC['run'](['sh', ROOT/'makemk.sh'], work, build)
            limbo = work/'tools/limbo'
        roots = work/'roots.m'
        roots.write_text('Roots: module { Node: adt { next: ref Node; }; copy: fn(source: array of ref Node): array of ref Node; caller: fn(padding: big, result: array of byte, tail: array of byte); many: fn('+', '.join('a'+str(i)+': array of byte' for i in range(150))+'); };')
        for module, modulefile in (('math', ROOT/'module/math.m'), ('roots', roots)):
            (work/(module+'-native64.h')).write_bytes(subprocess.check_output([str(limbo), '-H', str(modulefile)], cwd=work, env=env))
        includes = ['-I'+str(work)]+['-I'+str(ROOT/p) for p in ('Linux/386/include', 'emu/port', 'include', 'libinterp')]
        for label, selection in (('WORD32', ['-DDIS_WORD32=1']), ('WORD32-file', ['-DDIS_WORD32=1', '-DDIS64_PILOT_LOADER=1'])):
            command = compiler+flags+selection+includes+['-ffunction-sections', '-fdata-sections']
            objects = []
            for name in ('heap', 'math'):
                obj = work/(label+'-'+name+'.o')
                options = ['-DDIS_NATIVE64_MATH_HEADER="math-native64.h"'] if name == 'math' else []
                GC['run'](command+options+['-c', ROOT/('libinterp/'+name+'.c'), '-o', obj], work, env)
                objects.append(obj)
            for port in ('emu', 'os'):
                source = work/(label+'-'+port+'.c')
                source.write_text(unit(port))
                binary = work/(label+'-'+port)
                GC['run'](command+[source]+objects+['-Wl,--gc-sections', '-lm', '-o', binary], work, env)
                GC['run']([binary], work, env)
                print('PASS protected native64 result', port, label, flush=True)


if __name__ == '__main__':
    main()
