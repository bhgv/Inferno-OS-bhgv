#!/usr/bin/env python3
"""Derive handler names from the VM's authoritative opcode and dispatch tables."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[2]
isa = (root / 'include/isa.h').read_text()
isa = re.sub(r'/\*.*?\*/', '', isa, flags=re.S)
block = isa[isa.index('INOP'):isa.index('};')]
ops = [part.strip() for part in block.split(',') if part.strip()]
assert all(re.fullmatch(r'I[A-Z0-9]+', op) for op in ops)
text = (root / 'libinterp/optab.h').read_text()
text = re.sub(r'/\*.*?\*/', '', text, flags=re.S)
handlers = [part.strip() for part in text[text.index('{')+1:text.index('};')].split(',') if part.strip()]
assert len(ops) == len(handlers)
assert all(re.fullmatch(r'[A-Za-z_]\w*', name) for name in handlers)
output = '/* Generated by genops.py from isa.h and optab.h; do not edit by hand. */\n'
output += 'static const char *const handlers[MAXDIS] = {\n'
output += ''.join('\t['+op+'] = "'+name+'",\n' for op, name in zip(ops, handlers))
output += '};\ntypedef char opcode_count_must_match[MAXDIS == '+str(len(ops))+' ? 1 : -1];\n'
(root / 'utils/dis2c/ops.h').write_text(output)
