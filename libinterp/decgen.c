#include "lib9.h"
#include "isa.h"
#include "interp.h"

void decgen(int);


/* Emit all addressing-byte decoders and the stable public dispatch table. */
int
main(void)
{
	int i;

	print("/* Machine generated by decgen.c */\n\n");
	print("#include \"lib9.h\"\n");
	print("#include \"isa.h\"\n");
	print("#include \"interp.h\"\n");
	print("#include \"dec-addr.h\"\n\n");
	print("#define DIND(reg, xxx) decindirect(R.reg, pc.xxx.i.f, pc.xxx.i.s) // Read native pointer cells without alignment assumptions.\n");
	for(i = 0; i < 256; i++)
		decgen(i);
	print("\n\n/* Addressing byte indexes preserve the interpreter/JIT decoder ABI. */\n");
	print("void (*dec[])(void) =\n{\n");
	for(i = 0; i < 256; i++)
		print("\tDisDecode%.2uX%s\n", i, i != 255 ? "," : "");
	print("};\n");
	return 0;
}


/* Generate checked address formation while keeping immediate cells in the original Inst. */
void
decgen(int addr)
{
	int nodst;

	print("\n\n/* Decode addressing byte 0x%.2uX from a stable instruction image. */\n", addr);
	print("static void\nDisDecode%.2uX(void)\n{\n", addr);
	print("\tInst pc;\n\n\tdecinstruction(&pc);\n");
	switch(USRC(addr)){
	case AMP:
		print("\tR.s = decaddress(R.MP, pc.s.ind);\n");
		break;
	case AFP:
		print("\tR.s = decaddress(R.FP, pc.s.ind);\n");
		break;
	case AIMM:
		print("\tR.s = (uchar*)R.PC+O(Inst, s);\n");
		break;
	case AMP|AIND:
		print("\tR.s = DIND(MP, s);\n");
		break;
	case AFP|AIND:
		print("\tR.s = DIND(FP, s);\n");
		break;
	}
	nodst = 0;
	switch(UDST(addr)){
	default:
		nodst = 1;
		break;
	case AMP:
		print("\tR.d = decaddress(R.MP, pc.d.ind);\n");
		break;
	case AFP:
		print("\tR.d = decaddress(R.FP, pc.d.ind);\n");
		break;
	case AIMM:
		print("\tR.d = (uchar*)R.PC+O(Inst, d);\n");
		break;
	case AMP|AIND:
		print("\tR.d = DIND(MP, d);\n");
		break;
	case AFP|AIND:
		print("\tR.d = DIND(FP, d);\n");
		break;
	}
	if(nodst == 0){
		switch(addr&ARM){
		case AXNON:
			print("\tR.m = R.d;\n");
			break;
		case AXIMM:
			print("\tR.t = pc.reg < 32768 ? pc.reg : (int)pc.reg-65536;\n");
			print("\tR.m = &R.t;\n");
			break;
		case AXINF:
			print("\tR.m = decaddress(R.FP, pc.reg);\n");
			break;
		case AXINM:
			print("\tR.m = decaddress(R.MP, pc.reg);\n");
			break;
		}
	}
	print("}\n");
}
